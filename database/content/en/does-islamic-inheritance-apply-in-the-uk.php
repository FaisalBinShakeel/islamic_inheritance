<h2>Common questions</h2>
<h3>Do British courts recognise Sharia?</h3>
<p>A court giving effect to an Islamic will is not applying religious law. It is enforcing the instructions a person wrote down, exactly as it would for any other will. That is precisely why the document must satisfy ordinary English requirements.</p>
<h3>I have assets in Pakistan and in the UK. One will or two?</h3>
<p>Take advice. Assets in two countries often need wills in each, drafted so that neither accidentally revokes the other, and domicile affects which law governs what.</p>
<h3>My family will divide it properly anyway — do I still need a will?</h3>
<p>Without one, the executors are obliged to follow intestacy, not the family's intentions. Adult heirs can afterwards agree to redistribute what is theirs, but that depends on every one of them agreeing, being adult, and being willing. A will removes the need.</p>

