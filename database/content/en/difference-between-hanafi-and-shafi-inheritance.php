<p>Abu Hanifa held that the grandfather stands in the father's place, and a father excludes brothers — so the grandfather does too. That was the position reported from Abu Bakr and from Ibn Abbas. The other three schools follow Zayd b. Thabit: the grandfather shares, taking whichever is best for him of an equal brother's portion, a third of the residue, or a sixth of the whole estate.</p>
<p>This is the largest divergence in the system, and the one most likely to matter to a real family.</p>

<h2>2. Al-Akdariyya</h2>
<p>A follow-on from the first. A woman leaves her husband, her mother, her father's father and one full sister — and nothing else.</p>
<p>Under Hanafi rules the case never forms: the grandfather has already excluded the sister, so the husband takes a half, the mother a third, and the grandfather the remaining sixth. In the other three schools the shares first go to <em>awl</em> over nine, and then the grandfather and sister pool their portions and divide them two to one, producing the famous denominator of <strong>27</strong>.</p>

<h2>3. Al-Mushtaraka</h2>
<p>A woman leaves her husband, her mother, two maternal half-brothers and two full brothers. A half, a sixth and a third exhaust the estate exactly, leaving the full brothers — residuaries — with nothing.</p>
