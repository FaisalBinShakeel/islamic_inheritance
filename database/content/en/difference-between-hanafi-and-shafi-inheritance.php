<p>One point all four agree on: <strong>a surplus is never returned to a husband or wife.</strong></p>

<h2>What they all agree on</h2>
<p>Everything else, effectively. The spouse's half, quarter and eighth. The daughter's half and two thirds. The parents' sixths. The two-to-one ratio between sons and daughters. Maternal half-siblings dividing their third equally. Every rule of exclusion. <em>Awl</em>, which all four apply.</p>
