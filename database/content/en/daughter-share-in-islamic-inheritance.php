<p>"A daughter gets half of what a son gets" is the sentence most people know, and it is true only in one of the several positions a daughter can be in. In others she takes a fixed half of the entire estate, or shares two thirds with her sisters, and in some families she ends up with considerably more than that. This guide sets out every case with numbers. The <a href="/">calculator</a> will do your own case directly.</p>

<h2>The three positions</h2>
<h3>One daughter, no son: one half</h3>
<p>A single daughter with no brother takes 1/2 of the estate as a fixed share, named in the Qur'an (4:11). She takes it before the residuary heirs get anything.</p>

<h3>Two or more daughters, no son: two thirds shared</h3>
<p>Two daughters or more, with no brother, share 2/3 between them equally. Two daughters take a third each; three take 2/9 each.</p>

<h3>Daughters with a son: two to one</h3>
<p>When a son survives, the daughters stop being fixed-share heirs. Together with their brothers they take whatever is left after the fixed shares, with each brother taking twice each sister's portion.</p>
<p>This is the case the familiar sentence describes — and note what it actually applies to. The two-to-one ratio is applied to the <em>residue</em>, not to the whole estate.</p>

<h2>Worked examples</h2>
<h3>A daughter can take more than half the estate</h3>
<p>A man dies leaving a wife, his mother and one daughter, with an estate of PKR 2,400,000.</p>
<p>The wife takes 1/8 = 300,000. The mother takes 1/6 = 400,000. The daughter takes 1/2 = 1,200,000. That is 21/24, leaving 3/24 with no residuary heir to claim it — so <strong>radd</strong> applies. The surplus returns to the mother and the daughter in proportion to their shares, and never to the wife.</p>
