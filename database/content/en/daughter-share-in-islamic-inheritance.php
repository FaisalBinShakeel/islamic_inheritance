<h3>A daughter alone</h3>
<p>If a woman's only heir is one daughter, the daughter's fixed half is followed by radd of the other half to her, and she takes the whole estate.</p>

<h3>Daughters beside a son</h3>
<p>A man leaves a wife, two sons and three daughters, with PKR 4,750,000 after debts. The wife takes 1/8. The residue of 7/8 is divided into seven parts — four for the two sons, three for the three daughters. Each son receives about PKR 1,187,500 and each daughter about PKR 593,750.</p>

<h3>A daughter and the deceased's sister</h3>
<p>A man leaves one daughter and one full sister. The daughter takes her fixed 1/2. The sister does not take her usual half — the presence of a daughter turns her into a residuary, so she takes what is left, which is also 1/2. Many families assume the sister is excluded by the daughter. She is not.</p>

<h2>What about a son's daughter?</h2>
<p>If a son died before his father, that son's daughter can still inherit. Where there is no son and no daughter, she stands in a daughter's place and takes the half or the two thirds. Where there is exactly one daughter, the son's daughters share 1/6 — the sixth that completes the two thirds reserved for female descendants. Where there are two or more daughters, she is excluded, unless a son's son of her own level is present to make her a residuary.</p>
<p>In Pakistan there is a further rule that changes this substantially. Under section 4 of the Muslim Family Laws Ordinance 1961, the children of a son or daughter who died before the deceased take the share their parent would have taken. The calculator offers this as a separate option, because it is statute rather than fiqh.</p>

<h2>Common questions</h2>
<h3>Can a father leave everything to his daughter by will?</h3>
<p>No. A bequest is capped at one third of the estate and normally cannot go to someone who is already an heir. A daughter inherits by right, not by permission, and that right cannot be enlarged by a will without the other heirs' consent after death.</p>
<h3>Can a daughter be cut out of the estate?</h3>
<p>No. Her share is fixed by text. Property genuinely given away during the owner's lifetime is a different matter, and gifts made specifically to deprive an heir are contested ground — take that to a scholar.</p>
<h3>Does a married daughter still inherit?</h3>
<p>Yes. Marriage makes no difference to a daughter's share.</p>

