<h2>Without a will, the state decides</h2>
<p>Every state has intestacy statutes setting out who inherits and in what proportion. The details vary, but the shape is broadly similar: a surviving spouse takes a large portion, often the whole estate where all the children are also the spouse's; children share the rest; parents inherit only when there is no spouse and no descendant.</p>
<p>That last point is the sharpest divergence from Faraid, where each parent is entitled to a sixth whenever there is a child. Under most intestacy statutes, surviving parents receive nothing while a spouse and children exist.</p>
<p>Community property states add a further layer: a surviving spouse already owns half of the community property, so only the decedent's half is available to distribute at all.</p>

<h2>The elective share</h2>
<p>This is the provision that most often surprises people drafting an Islamic will in the US. In most non-community-property states, a surviving spouse who is left less than a statutory minimum can <strong>elect against the will</strong> and take that minimum anyway. The percentage and the method differ by state, and some calculate it on an augmented estate that reaches assets outside probate.</p>
<p>A will giving a widow one eighth is squarely in the territory the elective share was written for. It does not make the will invalid, but it does mean the distribution can be overridden if she chooses to claim. An attorney will want to talk about this directly rather than leave it to be discovered later.</p>

<h2>Assets that ignore your will entirely</h2>
<p>A great deal of American wealth passes outside probate, and a will has no effect on it:</p>
<ul>
    <li><strong>Retirement accounts</strong> — a 401(k) or IRA goes to the named beneficiary. For a 401(k), federal law generally requires a spouse to be the beneficiary unless they have consented in writing.</li>
    <li><strong>Life insurance</strong> — follows the policy beneficiary designation.</li>
    <li><strong>Joint accounts and property with right of survivorship</strong> — pass to the survivor automatically.</li>
    <li><strong>Transfer-on-death and payable-on-death designations.</strong></li>
</ul>
<p>Aligning these designations is usually more important than the wording of the will, because for many families they are where most of the money is.</p>

<h2>What an Islamic will typically covers</h2>
<ol>
