    <li>Funeral and burial instructions, and payment of debts — including unpaid <em>mahr</em>, which is a debt rather than a gift.</li>
    <li>A bequest of up to one third, usually to charity or to relatives who are not heirs.</li>
    <li>Distribution of the residue according to the Islamic shares.</li>
</ol>
<p>Some families use a revocable living trust instead of, or alongside, a will. That can avoid probate and gives more control over timing, but it does not by itself defeat an elective share, and it has to be funded properly to work at all.</p>

<h2>Will an American court apply Islamic law?</h2>
<p>A court is not applying religious law when it gives effect to an Islamic will. It is enforcing the instructions a person wrote down, as it would for any other will. That is precisely why the document has to satisfy ordinary state requirements — witnesses, capacity, execution — and why drafting it as a clear set of dispositive clauses matters more than the religious language around them.</p>

<h2>Common questions</h2>
<h3>Can I disinherit an adult child?</h3>
<p>In most states, yes — adult children have no forced share. That is not the problem an Islamic will runs into; the spousal elective share is.</p>
<h3>Do I need a will in each state where I own property?</h3>
<p>Usually one will is enough, but real estate in another state can require a separate probate there. Raise it with your attorney if you own property across state lines or abroad.</p>
<h3>What if my spouse is not Muslim?</h3>
<p>The classical rule on difference of religion, and how it interacts with a jurisdiction where a spouse has an elective share, is a question for a scholar and an attorney together. Both answers matter, and neither substitutes for the other.</p>

