</table>
<p>These are the two cases of Umar — <em>al-Gharrawayn</em>. Add any fourth heir and the doctrine stops applying: with a spouse, mother, father and one son, the mother simply takes her sixth.</p>

<h2>Worked example: a mother can take more than a third</h2>
<p>A man dies leaving his mother and one daughter, and an estate of PKR 1,800,000.</p>
<p>The mother takes 1/6 and the daughter 1/2 — that is two thirds. The remaining third has no residuary heir to claim it, so under the Hanafi and Hanbali schools it is returned to them in proportion:</p>
