<p>A mother's share looks like the simplest rule in Faraid and contains the single most commonly misapplied one. Two sentences cover the ordinary cases; the third catches people out. Your own case takes a minute in the <a href="/">calculator</a>.</p>

<h2>The rule</h2>
<p>From the Qur'an, 4:11:</p>
<ul>
    <li><strong>One third</strong> where the deceased left no child or grandchild, and fewer than two siblings.</li>
    <li><strong>One sixth</strong> where there is any child or agnatic grandchild, <em>or</em> where two or more siblings survive.</li>
</ul>
<p>"Child" here includes a daughter, and it includes a son's child. "Siblings" includes brothers, sisters, half-brothers and half-sisters of every kind.</p>

<h2>The rule that catches people out</h2>
<p><strong>Siblings reduce the mother's share even when those siblings inherit nothing at all.</strong></p>
<p>A man dies leaving his mother, his father and three sisters. The father excludes all three sisters — they receive not a rupee. But the mother still does not take her third:</p>
<table>
    <tr><th>Heir</th><th>Share</th></tr>
    <tr><td>Mother</td><td>1/6</td></tr>
    <tr><td>Father</td><td>5/6</td></tr>
    <tr><td>Three sisters</td><td>Nothing — excluded by the father</td></tr>
</table>
<p>Their presence alone is enough. Change it to a <em>single</em> sister and the mother goes back to a third, because the verse requires <em>ikhwa</em> — two or more.</p>
<p>This is the rule a hand calculation usually misses, because it feels wrong: how can someone who takes nothing change someone else's share? The answer is that the Qur'anic condition is about who survived, not about who inherits. There is more on this in <a href="/blog/who-is-excluded-from-islamic-inheritance">who is excluded from Islamic inheritance</a>.</p>

<h2>The case of Umar</h2>
<p>There is one configuration where the mother does not take a third of the estate even though nothing above applies. When the only survivors are a <strong>spouse, the mother and the father</strong>, she takes one third of what is left <em>after</em> the spouse — not a third of the whole.</p>
<table>
