</table>
<p>In the Maliki and Shafi'i schools that surplus goes to the public treasury instead, so the mother keeps her sixth and the daughter her half. The calculator shows both outcomes side by side; see <a href="/blog/awl-and-radd-explained">awl and radd explained</a>.</p>

<h2>What a mother does not lose</h2>
<p>Two things are often confused with her share and are not part of it. Her own property is hers and forms no part of her son's or daughter's estate. And anything she was genuinely given during their lifetime was a completed gift, not an advance on her inheritance.</p>

<h2>Common questions</h2>
<h3>Does a mother inherit from a married son?</h3>
<p>Yes. Marriage changes nothing. She takes her sixth alongside his widow and children.</p>
<h3>What if both parents survive but there are no children?</h3>
<p>The mother takes a third and the father takes the rest — twice her share. If a spouse also survives, see the case of Umar above, which changes the answer.</p>
<h3>Does a grandmother take the mother's share if the mother has died?</h3>
<p>No. A grandmother takes one sixth, shared between all grandmothers, and she is excluded entirely by the mother. A maternal grandmother is not excluded by the father; a paternal grandmother is.</p>

