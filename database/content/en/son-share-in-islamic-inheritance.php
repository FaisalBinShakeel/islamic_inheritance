<h2>Two to one, and what it is applied to</h2>
<p>Where sons and daughters inherit together, each son takes twice each daughter's portion. Note carefully what that ratio is applied to: the <strong>residue</strong>, after the fixed shares, not the whole estate. In the example above the daughters between them took more than the son did.</p>

<h2>When there is no son</h2>
<p>If a son died before his father, his own son — the deceased's grandson — steps into the same place, provided no living son of the deceased survives. A living son excludes him under the classical rules. In Pakistan, section 4 of the Muslim Family Laws Ordinance 1961 changes this and gives the predeceased son's family a share; the calculator offers that as a separate option, and <a href="/blog/islamic-inheritance-law-explained">the main guide</a> explains the background.</p>

<h2>Common questions</h2>
<h3>Can a father give his son more by writing a will?</h3>
<p>Not straightforwardly. A bequest is capped at one third and normally cannot go to someone who is already an heir. The remaining heirs can consent after death, but it cannot be imposed on them.</p>
<h3>Does an adopted son inherit?</h3>
<p>Not as a son, because the tie that creates inheritance is lineage. Provision can be made through the one-third bequest, which is exactly what it exists for.</p>
<h3>Does a son who cared for his parents get more?</h3>
<p>No. Faraid does not weigh conduct. What such a son may have is a claim as a creditor if there was a genuine debt, and debts are paid before any heir inherits.</p>
<h3>Why did my brother's share come out smaller than mine?</h3>
<p>If you are both sons, it should not — sons share the residue equally. If one of you is a half-brother through the father, a full brother excludes him. See <a href="/blog/who-is-excluded-from-islamic-inheritance">who is excluded</a>.</p>

