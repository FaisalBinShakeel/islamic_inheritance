<p>Unlike a daughter, a wife or a mother, a son has <strong>no fixed fraction</strong>. There is no verse giving him a half or a third. He is a residuary — he takes whatever remains after the fixed shares have been paid, which in one estate is seven eighths and in another is almost nothing. Enter your own heirs in the <a href="/">calculator</a> to see which.</p>

<h2>How a son actually inherits</h2>
<p>The order is always the same. First the deductions — funeral expenses, debts, a bequest of up to one third. Then the fixed shares to those the Qur'an names: the widow, the parents, sometimes a daughter. Whatever is left over goes to the nearest class of residuary heirs, and a son is the very first of them.</p>
<p>Being first in that order is what makes a son powerful in this system, more than any fraction would. He excludes the deceased's brothers, sisters, nephews, uncles and cousins completely. He reduces the widow from a quarter to an eighth and the mother from a third to a sixth. And he holds the father to a bare sixth.</p>

