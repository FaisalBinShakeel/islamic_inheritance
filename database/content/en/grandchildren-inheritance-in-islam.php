<h2>What a family can do without any of this</h2>
<p>Where the classical rules leave a grandchild with nothing, the <strong>bequest</strong> exists precisely for this. Up to one third of the estate may be left to someone who is not an heir, and an orphaned grandchild excluded by a living son is not an heir. Making that bequest during life is the straightforward answer, and it is strongly encouraged where the grandchildren are in need.</p>
<p>Adult heirs may also agree, after the shares are established, to give part of their own portions. That is theirs to give — but only once everyone knows what they are giving up.</p>

<h2>Common questions</h2>
<h3>Is the classical rule unfair to orphaned grandchildren?</h3>
<p>It is a real difficulty, and the answer the tradition gives is the one-third bequest, which exists for exactly the people the fixed shares do not reach. Whether statute should go further is the argument section 4 sits in the middle of.</p>
<h3>Does a grandson inherit if his father is alive but estranged?</h3>
<p>No. A living son takes his own share, and his children inherit from him in due course. Representation only arises where the parent died first.</p>
