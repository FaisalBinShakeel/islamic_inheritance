<h2>The classical rule: nearer excludes further</h2>
<p>A son's son inherits as a residuary, in the place a son would occupy — but only if <strong>no son of the deceased survives</strong>. One living son excludes every grandson through another son.</p>
<p>So a man with three sons, one of whom died before him leaving two boys, divides his estate between the two living sons. His grandsons receive nothing under classical rules.</p>
<p>The principle is consistent — a nearer relative removes a further one, and it is the same rule by which a son removes the deceased's brothers. But the outcome in this particular case has troubled jurists and legislators for a long time.</p>

<h2>Granddaughters through a son</h2>
<p>A son's daughter has three possible positions:</p>
<ul>
    <li><strong>No son and no daughter of the deceased survives:</strong> she stands in a daughter's place — one takes 1/2, two or more share 2/3.</li>
    <li><strong>Exactly one daughter survives:</strong> the son's daughters share <strong>1/6</strong>, the sixth that completes the two thirds reserved for female descendants.</li>
    <li><strong>Two or more daughters survive:</strong> she is excluded, because the two thirds is already taken — unless a son's son of her own level is present, who makes her a residuary alongside him at two to one.</li>
</ul>

<h2>Children of a daughter</h2>
<p>Under the classical rules a daughter's children are <em>dhawu al-arham</em> — distant kindred. They inherit only where no fixed-share heir and no residuary survives at all, and the schools differ even on that. This calculator does not attempt distant kindred, and says so when the situation arises.</p>

