<h2>Common questions</h2>
<h3>Do the four schools disagree about Faraid?</h3>
<p>Far less than about almost anything else, because the shares are explicit text. They differ on a handful of configurations — most visibly a grandfather competing with brothers. See <a href="/blog/difference-between-hanafi-and-shafi-inheritance">where the schools differ</a>.</p>
<h3>Why are the fractions what they are?</h3>
<p>They are given in the text, not derived. The system is best understood as a fixed allocation that also carries obligations — the male heirs who take larger portions also carry maintenance duties that the female heirs do not.</p>
