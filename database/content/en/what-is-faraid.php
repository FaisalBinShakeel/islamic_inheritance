<p><em>Faraid</em> — from <em>farida</em>, an obligatory portion — is the branch of Islamic law that decides who inherits from an estate and exactly how much. In Urdu it is usually <em>meeras</em> or <em>wirasat</em>; in Arabic also <em>ilm al-mawarith</em>. If you want the answer for your own family rather than the theory, the <a href="/">calculator</a> gives it in about a minute.</p>

<h2>Why it is called a science</h2>
<p>Most of Islamic law works by reasoning from texts to a ruling, and reasonable scholars reach different answers. Faraid is unusual: the Qur'an names the heirs and states their fractions outright, in three verses of Surah al-Nisa — 4:11, 4:12 and 4:176. There is very little room left for opinion.</p>
<p>What remains is arithmetic, and the arithmetic is genuinely intricate. Six fractions have to be fitted to any combination of surviving relatives, with rules deciding who removes whom, and remedies for when the fractions do not add up to exactly one estate. That is why it was taught as a separate discipline, and why a hadith is reported urging that it be learned and taught.</p>

<h2>What the system actually consists of</h2>
<ol>
    <li><strong>Deductions first.</strong> Funeral expenses, then debts, then a bequest of up to one third. What remains is the estate that gets divided. Nothing else happens until this is settled.</li>
    <li><strong>Fixed shares.</strong> Twelve or so categories of heir have a named fraction — a half, a quarter, an eighth, two thirds, a third or a sixth. Nothing outside those six fractions exists.</li>
    <li><strong>The residue.</strong> Whatever is left goes to the nearest surviving class of <em>asaba</em> — sons first, then the father's line, then brothers, then uncles. The first class present takes everything left.</li>
    <li><strong>Exclusion.</strong> A nearer relative removes a further one. A son removes the uncles; a father removes the grandfather.</li>
    <li><strong>The remedies.</strong> When the fixed shares claim more than the estate, everyone is reduced in proportion (<em>awl</em>). When they leave a surplus with no residuary to take it, it is returned (<em>radd</em>).</li>
</ol>
<p>The step-by-step version, with a full worked case, is in <a href="/blog/how-is-inheritance-divided-in-islam">how inheritance is divided in Islam</a>.</p>

<h2>What Faraid is not</h2>
<p>It is <strong>not a will</strong>. A will (<em>wasiyyah</em>) can dispose of up to a third, normally to someone who is not already an heir. Faraid governs the rest, and it cannot be overridden by preference.</p>
<p>It is <strong>not a family agreement</strong>. Adult heirs may of course give away what is theirs once the shares are established — but "we agreed to do it differently" is only meaningful if everyone knew what they were giving up.</p>
<p>It is <strong>not automatically the law where you live</strong>. In Pakistan it is the default legal position. In the UK, the US, Canada and Australia it is not, and without a valid will local intestacy rules apply instead. See <a href="/blog/islamic-will-uk">Islamic wills in the UK</a>.</p>

