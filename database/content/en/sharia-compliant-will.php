<h2>What the fiqh requires</h2>
<h3>Debts before everything</h3>
<p>Funeral expenses, then every debt the deceased owed. Two are routinely forgotten: <strong>unpaid mahr</strong>, which is a debt of the estate and not a gift, and money borrowed informally from relatives. Both are paid in full before any heir inherits.</p>

<h3>A bequest of no more than one third</h3>
<p>The cap comes from the hadith of Sa'd b. Abi Waqqas, who asked whether he could give away two thirds, then half, and was told: one third, "and one third is a great deal". It is a maximum, not a target.</p>

<h3>Normally not to an existing heir</h3>
<p>A bequest cannot ordinarily be used to give a son or a daughter more than their share, because that would rewrite the fixed shares by another route. The remaining heirs may consent after death, but nothing can be imposed on them.</p>
<p>This is what makes the third so useful for the people the fixed shares do not reach: an <a href="/blog/grandchildren-inheritance-in-islam">orphaned grandchild excluded by a living son</a>, a non-Muslim parent, an adopted child, a charity.</p>

<h3>The rest by the fixed shares</h3>
<p>Whatever remains is divided by Faraid. A will does not get to choose those proportions.</p>

<h2>What the local law requires</h2>
<p>This is where home-made wills fail, and the requirements vary by country. Some constants worth knowing:</p>
<ul>
    <li><strong>Witnesses.</strong> Most common-law jurisdictions need two. Critically, <strong>a beneficiary or a beneficiary's spouse must not witness the will</strong> — the will usually stays valid but their gift is void. Having your son or your brother's wife witness it can quietly destroy the very distribution you were securing.</li>
    <li><strong>Forced shares.</strong> Several jurisdictions guarantee a surviving spouse a minimum regardless of the will. In much of the United States this is the elective share; France reserves a fixed portion for children that a will cannot override at all.</li>
    <li><strong>Claims by dependants.</strong> England and Wales allow certain people to ask a court for reasonable provision even where the will is valid.</li>
    <li><strong>Assets that ignore the will entirely.</strong> Jointly held property, pension nominations and life policies usually pass outside the estate. Aligning those designations often matters more than the wording of the will.</li>
</ul>
