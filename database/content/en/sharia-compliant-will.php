<h2>Fixed fractions, or a reference?</h2>
<p>A drafter has to choose between writing the actual fractions into the will and directing that the estate be distributed according to Islamic law generally.</p>
<p>Fixed fractions are unambiguous and easy for an executor to apply — but they go out of date the moment your family changes. A child is born, a parent dies, and the will now describes a family that no longer exists. A general direction survives those changes but leaves the executor to do the calculation, and a court may want to know which rules were meant.</p>
<p>Most drafters use a general direction plus a schedule showing the shares as at the date of the will. Discuss it with the solicitor rather than deciding it yourself.</p>

<h2>Common questions</h2>
<h3>Can I download a template?</h3>
<p>Templates are useful for understanding the structure and risky as a final document — the failure modes are witnesses, forced shares and assets passing outside the estate, and a template cannot see any of those in your case.</p>
<h3>Does a will have to mention Islam?</h3>
<p>No. Legal effect comes from the dispositive clauses. Many Islamic wills recite the intention because it helps the family understand the structure.</p>
<h3>How often should it be reviewed?</h3>
<p>After any marriage, divorce, birth or death, and after moving country or acquiring assets abroad. In England, marriage revokes a will unless it was made in contemplation of that marriage.</p>

