<p>A wife's share is one of the simplest rules in Faraid and one of the most often misapplied, usually in the same two ways: giving each of several wives a full share, and returning a surplus to a widow who is not entitled to it. Both are worked through below. Your own case takes a minute in the <a href="/">calculator</a>.</p>

<h2>The rule</h2>
<p>From the Qur'an, 4:12:</p>
<ul>
    <li><strong>One quarter</strong> if the husband left no child and no agnatic grandchild.</li>
    <li><strong>One eighth</strong> if he did.</li>
</ul>
<p>A husband's mirror share is one half, falling to one quarter when there are children.</p>

<h2>Co-wives divide one share, not one each</h2>
<p>This is the error worth being loudest about. The Qur'anic text assigns the share to the wives collectively. If a man leaves four widows and two children, the widows do not take an eighth each — they take an eighth <strong>between them</strong>, a thirty-second apiece.</p>
<p>The "child" that triggers the reduction need not be the wife's own. A child from any marriage reduces every wife's share, and so does a son's child.</p>

<h2>A surplus never returns to a widow</h2>
<p>When the fixed shares leave a surplus and no residuary heir survives, the surplus is returned to the fixed-share heirs in proportion. A spouse is excluded from that return.</p>
<p>A man dies leaving a wife and one daughter, with an estate of PKR 800,000. The wife takes 1/8 = 100,000. The daughter takes her fixed 1/2 = 400,000. The remaining 300,000 has no residuary to claim it, so it returns to the daughter alone.</p>
<table>
    <tr><th>Heir</th><th>Fixed share</th><th>After radd</th><th>Amount</th></tr>
    <tr><td>Wife</td><td>1/8</td><td>1/8</td><td>100,000</td></tr>
    <tr><td>Daughter</td><td>1/2</td><td>7/8</td><td>700,000</td></tr>
</table>
<p>Where a widow is the <em>only</em> heir, this calculator does not quietly hand her the rest. It shows her quarter and reports the remainder as undistributed, because classically that surplus goes to the public treasury — a point covered on the <a href="/methodology">methodology page</a>.</p>

<h2>Two more worked cases</h2>
<h3>A wife with sons and daughters</h3>
<p>PKR 4,750,000, one wife, the deceased's mother, two sons and three daughters. The wife takes 1/8 = 593,750 and the mother 1/6 = 791,667. The rest is split between the children, two to one.</p>

<h3>A wife where awl applies</h3>
<p>One wife, two daughters, the father and the mother. The shares come to 3/24 + 16/24 + 4/24 + 4/24 = 27/24 — more than the estate. Awl raises the denominator to 27, and the wife's eighth becomes a ninth. This case is famous: it was put to Ali b. Abi Talib on the pulpit at Kufa, and it is known as <em>al-Minbariyya</em> for that reason. It is explained in <a href="/blog/awl-and-radd-explained">awl and radd explained</a>.</p>

<h2>A widow's other entitlements</h2>
<p>Two things are commonly confused with inheritance and are not part of it:</p>
<ul>
    <li><strong>Unpaid <em>mahr</em>.</strong> Deferred dower is a debt of the estate. It is paid in full before any heir inherits — and then the widow still takes her share as an heir on top.</li>
    <li><strong>Her own property.</strong> Whatever a wife owns is hers. It is not part of her husband's estate and is not divided.</li>
</ul>

<h2>Common questions</h2>
<h3>Does a widow inherit if the marriage had problems?</h3>
<p>A valid marriage at the time of death means she inherits. Where a divorce was in progress, whether it was complete matters, and the answer depends on the type of divorce and the stage reached. That is a question for a scholar with the facts in front of them.</p>
<h3>Does she keep the family home?</h3>
<p>The house is part of the estate and is divided like everything else. Her share of it is her share; it does not pass to her whole. Families often agree to leave a widow in the home, which is theirs to agree once the shares are established.</p>
<h3>Does my wife inherit automatically if I live in the UK or the US?</h3>
<p>Not in these proportions. Without a valid will, local intestacy law decides — and it usually gives a spouse far more than an eighth and the children far less. See <a href="/blog/islamic-will-uk">Islamic wills in the UK</a>.</p>

