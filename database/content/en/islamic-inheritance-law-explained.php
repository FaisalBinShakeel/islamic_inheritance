<h2>When the arithmetic does not land exactly</h2>
<p>Sometimes the fixed shares add up to more than the whole estate, and sometimes to less with nobody left to take the remainder. Both have names and both have fixed remedies — <em>awl</em> and <em>radd</em>. They are explained with worked examples in <a href="/blog/awl-and-radd-explained">awl and radd explained</a>.</p>

<h2>Common questions</h2>
<h3>Can the heirs simply agree to divide it differently?</h3>
<p>Adult heirs can, after the shares have been established, agree among themselves to give up or exchange what is theirs. What cannot happen is for the division itself to be decided by preference rather than by the rules. Knowing the correct shares first is what makes any later agreement genuinely voluntary.</p>
<h3>Does a daughter really get half of what a son gets?</h3>
<p>Where they inherit together as residuaries, yes. But that is only one of several positions a daughter can occupy, and in some cases she takes a fixed half of the whole estate. See <a href="/blog/daughter-share-in-islamic-inheritance">the daughter's share in Islamic inheritance</a>.</p>
<h3>Do these shares apply automatically where I live?</h3>
<p>In Pakistan, yes. In the UK, the US, Canada, Australia and much of Europe, no — without a valid will, local intestacy law applies instead. See <a href="/blog/islamic-will-uk">Islamic wills in the UK</a>.</p>

