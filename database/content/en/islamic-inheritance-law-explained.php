<p>Islamic inheritance — <em>faraid</em> — is not a percentage split decided by the family. It is a fixed system: the Qur'an names certain heirs and gives each of them a defined fraction, and what is left over goes to a second group in a strict order of nearness. This guide walks through the whole thing, then works a real case end to end. If you would rather see your own answer first, the <a href="/">calculator</a> will do it in under a minute.</p>

<h2>Four things happen before anyone inherits</h2>
<p>Shares are never calculated on the gross estate. Three amounts come off the top, in this order:</p>
<ol>
    <li><strong>Funeral and burial expenses.</strong></li>
    <li><strong>Debts.</strong> Everything the deceased owed, to people or to institutions.</li>
    <li><strong>A bequest (<em>wasiyyah</em>)</strong>, if one was made — but no more than one third of whatever is left after the first two, and normally only to someone who is not already an heir.</li>
</ol>
<p>The one-third limit comes from a hadith in which Sa'd b. Abi Waqqas asked the Prophet ﷺ whether he could give away two thirds, then half, and was told: one third, "and one third is a great deal". What remains after all three deductions is the estate that actually gets divided.</p>

<h2>Only six fractions exist</h2>
<p>Every fixed-share heir receives one of exactly six fractions, and no others: <strong>1/2, 1/4, 1/8, 2/3, 1/3, 1/6</strong>. Which one an heir gets depends on who else survived.</p>
<p>The best example is the spouse. A husband takes one half if his wife left no children or grandchildren, and one quarter if she did. A wife takes one quarter if there are no children, one eighth if there are — and however many wives there are, they divide that single share between them. Four wives do not take an eighth each; they take an eighth between them. There is a full explanation in <a href="/blog/wife-share-in-islamic-inheritance">the wife's share in Islamic inheritance</a>.</p>

<h2>Then the residue</h2>
<p>Once the fixed shares are paid, whatever remains goes to the <em>asaba</em> — the residuary heirs — in a strict order of nearness. The first surviving class takes everything and completely excludes every class below it:</p>
<ol>
    <li>Sons, then sons' sons, and so on downwards</li>
    <li>The father, then the father's father</li>
    <li>Full brothers, then paternal half-brothers, then their sons</li>
    <li>Full paternal uncles, then paternal half-uncles, then their sons</li>
</ol>
<p>Within a class, a male takes twice the share of a female where both inherit together. There is one striking exception in the whole system: maternal half-siblings divide their third <em>equally</em>, a brother and a sister taking exactly the same.</p>

<h2>Exclusion</h2>
<p>A nearer heir removes a further one entirely. A son excludes the deceased's brothers. A father excludes his own father. A mother excludes every grandmother. This is why a family can be surprised to find that an uncle who expected a share receives nothing. The full picture is in <a href="/blog/who-is-excluded-from-islamic-inheritance">who is excluded from Islamic inheritance</a>.</p>
<p>There is a subtler rule worth knowing, because simple calculators get it wrong. Siblings reduce the mother's share from a third to a sixth <strong>even when those same siblings are themselves excluded by the father and inherit nothing</strong>. Their presence alone is enough.</p>

<h2>A worked example</h2>
<p>A man dies leaving an estate of PKR 5,000,000. Funeral expenses were PKR 50,000 and he owed PKR 200,000. He is survived by one wife, his mother, two sons and three daughters.</p>
<p>First the deductions: 5,000,000 − 50,000 − 200,000 = <strong>PKR 4,750,000</strong> to divide.</p>
<p>Then the fixed shares. The wife takes one eighth, because there are children. The mother takes one sixth, for the same reason. That is 3/24 + 4/24 = 7/24, leaving <strong>17/24</strong> as residue.</p>
<p>The sons and daughters take that residue two to one. Two sons count as four shares, three daughters as three, seven in total. The sons take 4/7 of 17/24 and the daughters 3/7.</p>
