<h2>Common questions</h2>
<h3>What if the heirs cannot agree on the value of the property?</h3>
<p>The shares are fractions, so they hold whatever the valuation turns out to be. Establish the shares first and value the property second; doing it the other way round tends to turn a valuation dispute into an inheritance dispute.</p>
<h3>What if one heir has already received money during the deceased's lifetime?</h3>
<p>A genuine completed gift made during life is not part of the estate and is not deducted from that heir's share. A dispute about whether it was a gift or a loan is a factual question for a scholar or a court, not an arithmetic one.</p>
<h3>Can I do this without knowing which school my family follows?</h3>
<p>For most estates, yes — the four schools agree on the great majority of cases. They differ mainly when a grandfather competes with brothers. The calculator asks for the school anyway rather than guessing.</p>

