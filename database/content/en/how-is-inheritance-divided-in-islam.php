<h2>Step 5 — Give the residue to the nearest residuary</h2>
<p>Whatever is left goes to the first surviving class in this order: sons and their line; then the father and his father; then full brothers, half-brothers and their sons; then uncles and their sons. The first class present takes everything left, and the rest get nothing. Where men and women inherit together in this group, the male takes two shares to the female's one.</p>

<h2>Step 6 — Check that it balances</h2>
<p>Add the shares up. If they come to exactly the estate, you are done. If they come to <em>more</em>, apply awl: raise the denominator to the total and reduce everyone in proportion. If they come to <em>less</em> and no residuary survived, apply radd: return the surplus to the fixed-share heirs in proportion, but never to a husband or wife. Both are worked through in <a href="/blog/awl-and-radd-explained">awl and radd explained</a>.</p>

