<h2>Step 1 — Establish the net estate</h2>
<p>Add up everything owned at death: property, cash, gold, business share, receivables. Then subtract, in order, the funeral costs, every outstanding debt, and any valid bequest up to one third of what remains. The figure left is what you divide.</p>
<p>Do not skip the debts. They come before the heirs entirely, even if that leaves the heirs with nothing.</p>

<h2>Step 2 — List who survived, precisely</h2>
<p>Write down every surviving relative with their exact relationship. "Brother" is not enough: a full brother, a paternal half-brother and a maternal half-sibling inherit completely differently. The same goes for grandmothers — the mother's mother and the father's mother are excluded by different people.</p>
<p>Two people are removed at this stage and do not count for anything afterwards: an heir who unlawfully killed the deceased, and, under the classical rule, an heir of a different religion.</p>

<h2>Step 3 — Cross out whoever is excluded</h2>
<p>Work down from the nearest relatives. A son excludes all brothers, sisters, nephews and uncles. A father excludes the grandfather and all siblings. A mother excludes every grandmother. Any child or grandchild excludes maternal half-siblings.</p>
<p>Keep the crossed-out names on the paper. Relatives always ask why they received nothing, and the answer — "your uncle was excluded by the deceased's son" — is easier to give with the list in front of you.</p>

<h2>Step 4 — Give out the fixed shares</h2>
<p>Now assign the six fractions. In most estates only three or four apply:</p>
<ul>
    <li><strong>Husband:</strong> 1/2, or 1/4 if there are children or grandchildren.</li>
    <li><strong>Wife or wives together:</strong> 1/4, or 1/8 if there are children or grandchildren.</li>
