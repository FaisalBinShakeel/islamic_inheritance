<h2>Paternal half-siblings</h2>
<p>They inherit like full siblings, but stand behind them. A full brother excludes them entirely. Two full sisters, having taken the whole two thirds, exclude a paternal half-sister — unless she has a brother of her own to make her a residuary. Where exactly one full sister survives, the paternal half-sisters take <strong>1/6</strong>, completing the two thirds.</p>

<h2>Common questions</h2>
<h3>My father left children — do his brothers get anything?</h3>
<p>If he left a son, no. If he left only daughters, the brothers may take the residue after the daughters' two thirds — so the answer depends on whether any son survived.</p>
<h3>Are step-siblings included?</h3>
<p>Only if you share a parent. A step-sibling with no parent in common is not an heir, and has no share.</p>
<h3>Does a sister who is financially comfortable still inherit?</h3>
<p>Yes. Need plays no part in the calculation, and her share is hers to give away afterwards if she chooses.</p>

